#pragma once

#include "MathUtility.h"   // Matrix4x4

// ════════════════════════════════════════════════════════════════════
// 描画時に「今のカメラ」をまとめて配るための箱
//   ・どのカメラ（編集／ゲーム）かは Editor が決める
//   ・描く側はこの箱だけ見ればよく、カメラの実体を知らなくてよい
//
//   必要な情報が増えたらここにメンバを足すだけでよく、
//   各 Draw の宣言を書き換える必要がない
// ════════════════════════════════════════════════════════════════════
struct CameraData {
	Matrix4x4 viewMatrix{};             // 世界をカメラ基準に直す
	Matrix4x4 projectionMatrix{};       // 3Dを画面に潰す
	Matrix4x4 viewProjectionMatrix{};   // 上2つを合成したもの（使用頻度が高いので持つ）
	Vector3   worldPosition{};          // カメラの位置。鏡面反射の視線計算に使う
};