#include "MyGame.h"

// ════════════════════════════════════════════════════════════════════
// 初期化
// ════════════════════════════════════════════════════════════════════
void MyGame::Initialize() {

	//   エンジンの道具を先に作る
	//     これより前に GetContext() を呼んでも、中身は空
	Framework::Initialize();

	gameScene_.Initialize(GetContext());
}

// ════════════════════════════════════════════════════════════════════
// 更新
//   時間・入力・ImGui のフレーム開始は Framework が済ませている
// ════════════════════════════════════════════════════════════════════
void MyGame::Update() {
	gameScene_.Update();
}

// ════════════════════════════════════════════════════════════════════
// 描画
//   PreDraw / PostDraw と ImGui の描画は Framework が包んでいる
// ════════════════════════════════════════════════════════════════════
void MyGame::Draw() {
	gameScene_.Draw();
}