#include "Camera.h"

#include "WinApp.h"

// ════════════════════════════════════════════════════════════════════
// 初期化
// ════════════════════════════════════════════════════════════════════
void Camera::Initialize() {

	// アスペクト比は画面サイズから求める
	aspectRatio_ = static_cast<float>(WinApp::kClientWidth)
		/ static_cast<float>(WinApp::kClientHeight);

	// 既定値で行列を1回作っておく
	//   Update を呼び忘れても単位行列のまま描画されない
	Update();
}

// ════════════════════════════════════════════════════════════════════
// 行列の更新
// ════════════════════════════════════════════════════════════════════
void Camera::Update() {

	// ────────────────────────────────────────
	// ① ワールド行列
	//     ワールド基準で、カメラはどこにいて、どちらを向いているか
	//     カメラ自身は拡縮しないのでスケールは単位
	// ────────────────────────────────────────
	worldMatrix_ = MakeAffineMatrix({ 1.0f, 1.0f, 1.0f }, rotate_, translate_);

	// ────────────────────────────────────────
	// ② ビュー行列＝ワールド行列の逆行列
	//
	//   やりたいこと ： カメラ基準の座標が欲しい
	//   計算方法     ： 世界全体を、カメラが原点に来るようにずらす
	//   結果         ： ずらした後の座標 ＝ カメラ基準の座標
	// ────────────────────────────────────────
	viewMatrix_ = Inverse(worldMatrix_);

	// ────────────────────────────────────────
	// ③ 射影行列（透視投影）
	//     遠いものほど小さく見えるようにして、2D画面に奥行きを出す
	//     視錐台（四角すいを切り取った形）の中だけが映る
	// ────────────────────────────────────────
	projectionMatrix_ = MakePerspectiveMatrix(fovY_, aspectRatio_, nearClip_, farClip_);
	/*
	* MakePerspectiveMatrix(0.45f, 1280.0f / 720.0f, 0.1f, 100.0f);
							   ↑         ↑            ↑      ↑
							  fovY    aspectRatio   nearClip farClip


		引数	            値	                    意味
		fovY	        0.45（ラジアン、約26度）	縦方向の画角。カメラのレンズの広さ
		aspectRatio	    1.778（16:9）	        画面の横÷縦
		nearClip	    0.1	                    これより近いものは映さない
		farClip	        100.0	                これより遠いものは映さない
	*/
	// ────────────────────────────────────────
	// ④ 合成しておく
	//     描画するオブジェクトの数だけ掛け算するのは無駄なので、1回だけ計算する
	// ────────────────────────────────────────
	viewProjectionMatrix_ = viewMatrix_ * projectionMatrix_;
}